import { describe, expect, it } from "vitest"
import { parseWill } from "../../../app/javascript/live_protocol/will_parser.js"

describe("parseWill", () => {
  it.each([
    ["234к, 67ч, 9ш", [2, 3, 4], [6, 7], [9], ""],
    ["2 3 4 r 6 7 b 9 s", [2, 3, 4], [6, 7], [9], ""],
    ["234r, 67b, 9s", [2, 3, 4], [6, 7], [9], ""],
    ["10к, 1ч", [10], [1], [], ""],
    ["0к", [10], [], [], ""],
    ["210к стреляйте в 8 завтра", [2, 10], [], [], "стреляйте в 8 завтра"],
    ["просто план", [], [], [], "просто план"],
    ["", [], [], [], ""],
    ["234К, 67Ч, 9Ш", [2, 3, 4], [6, 7], [9], ""],
    ["234R 67B 9S", [2, 3, 4], [6, 7], [9], ""],
    ["1к 2к", [1, 2], [], [], ""],
    ["стреляйте в 8, 3ч", [], [3], [], "стреляйте в 8"],
    ["2 красных", [], [], [], "2 красных"],
    ["2 черных и 3 шерифа", [], [], [], "2 черных и 3 шерифа"],
    ["  план  ", [], [], [], "план"],
    ["план   два", [], [], [], "план два"],
    ["1 0к", [10], [], [], ""],
    ["1к,   план,   2ч", [1], [2], [], "план"]
  ])("reads %j", (raw, red, black, sheriff, plan) => {
    expect(parseWill(raw)).toEqual({ red, black, sheriff, plan })
  })
})
